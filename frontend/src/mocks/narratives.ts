/**
 * 取 Mock 叙事结果。
 * 如果库中没有对应组合，回退到小明的同风格结果（保持 UI 可用）。
 */
export function getMockNarrative(
  agentId: string,
  style: NarrativeStyle,
): NarrativeResult {
  const key = `${agentId}:${style}`;
  const direct = MOCK_NARRATIVE_LIBRARY[key];
  if (direct) {
    // 重新生成时刷新时间戳，模拟"新生成"
    return { ...direct, generated_at: new Date().toISOString() };
  }
  // 回退：用小明的同风格结果，但替换 agent 信息
  const fallback = MOCK_NARRATIVE_LIBRARY[`mock-1:${style}`];
  if (fallback) {
    return {
      ...fallback,
      agent_id: agentId,
      generated_at: new Date().toISOString(),
    };
  }
  // 最终兜底（理论上不会走到）
  return {
    title: "（暂无示例叙事）",
    content: "该 Agent 暂未预置叙事示例，请尝试其他 Agent 或等待后端接入。",
    style,
    agent_id: agentId,
    agent_name: "未知",
    generated_at: new Date().toISOString(),
    word_count: 0,
  };
}

/** 计算中文字数——简单按字符数（不含空白） */
export function countWords(text: string): number {
  return text.replace(/\s/g, "").length;
}

/**
 * 解析 Agent 选择——从 MOCK_AGENTS 与 store 合并的列表中取。
 * 这里不直接依赖 useAgentStore，由页面层传入，保持纯函数特性。
 */
export function pickAgentName(
  agents: AgentResponse[],
  agentId: string,
): string {
  return agents.find((a) => a.id === agentId)?.name ?? "未知";
}
