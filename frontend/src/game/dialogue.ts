/** 缺省兜底对话（当组合不存在时） */
const FALLBACK: Record<Scene, string[]> = {
  library:    ["这里好安静","你在看什么书","别吵到别人"],
  dorm:       ["外卖到了吗","今天好累","早点休息"],
  classroom:  ["这题怎么做","快下课了","笔记借我"],
  art:        ["这里好有氛围","你也在创作吗","灵感来了"],
  lab:        ["数据怎么样","实验结果如何","注意安全"],
  sakura:     ["花好美","春天真好","拍张照吧"],
};

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function getDialogue(fromName: string, toName: string, sceneId: string): string {
  const speakerPool = (POOL as any)[fromName];
  if (speakerPool) {
    const listenerPool = speakerPool[toName];
    if (listenerPool) {
      const sceneLines = listenerPool[sceneId];
      if (sceneLines && sceneLines.length > 0) return pick(sceneLines);
    }
  }
  // fallback: 通用场景对话
  const lines = FALLBACK[sceneId as Scene] ?? FALLBACK.library;
  return pick(lines);
}
